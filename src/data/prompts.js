// 칸을 채운 완성본: 빈칸은 [칸 이름]으로 남깁니다.
export function fillPrompt(p, values = {}) {
  return p.template.replace(/\{\{(\w+)\}\}/g, (_, k) => {
    const v = (values[k] || '').trim()
    if (v) return v.includes('\n') ? `\n${v}` : v
    const f = p.fields.find(x => x.key === k)
    return `[${f ? f.label : k}]`
  })
}
