TOOLS = ['ChatGPT', 'Gemini', 'Claude', 'NotebookLM', '클로바노트', 'Perplexity', 'Canva', 'Notion', '노션']
def assemble(mid, body):
    m = MM[mid]
    for a, b in FIX.get(mid, []): body = body.replace(a, b)
    if mid in EXTRA:
        # 첫 장 끝(두 번째 # 제목 앞)에 넣습니다
        idx = [x.start() for x in re.finditer(r'^# ', body, re.M)]
        pos = idx[1] if len(idx) > 1 else len(body)
        body = body[:pos] + EXTRA[mid] + '\n\n' + body[pos:]
    chk, links = GROUP_END[m['group']]
    # 원고의 마지막 장이 맺음말이면 그 앞에 점검표를 넣지 않고 끝에 붙입니다
    body = body.rstrip() + '\n\n' + chk + '\n\n' + links + '\n'
    tools = [t for t in TOOLS if t in body]
    tools = ['Notion' if t == '노션' else t for t in tools]
    tools = list(dict.fromkeys(tools))[:5] or ['ChatGPT', 'Gemini', 'Claude']
    summ = m['desc'].replace('\n', ' ')
    return f"---\nsummary: {summ}\nwho: 재학생 전체\ntools: {', '.join(tools)}\n---\n\n" + body

